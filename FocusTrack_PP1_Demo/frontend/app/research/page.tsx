"use client"

import { useCallback, useEffect, useState } from "react"
import { FlaskConical, Download, RefreshCw, AlertTriangle } from "lucide-react"
import { AppShell } from "@/components/layout/app-shell"
import { Card } from "@/components/ui/card"
import { Bars, Legend, SessionTrace, Stat } from "@/components/research/charts"
import { generateStudy } from "@/lib/sim/generate"
import { labelStats, runC1, runC2, runC3, runC4, type AllResults } from "@/lib/sim/analysis"
import type { SimStudy } from "@/lib/sim/types"

const TABS = ["Overview & labelling", "C1 Behaviour", "C2 Environment", "C3 Vision", "C4 Temporal & XAI"] as const
type Tab = (typeof TABS)[number]
const pct = (v: number) => `${(v * 100).toFixed(1)}%`
const p3 = (v: number) => (Number.isFinite(v) ? (v < 0.001 ? "< 0.001" : v.toFixed(3)) : "n/a")
const pause = () => new Promise((r) => setTimeout(r, 30))

export default function ResearchPage() {
  const [seed, setSeed] = useState(2026)
  const [tab, setTab] = useState<Tab>("Overview & labelling")
  const [status, setStatus] = useState("")
  const [study, setStudy] = useState<SimStudy | null>(null)
  const [res, setRes] = useState<Partial<AllResults>>({})

  const run = useCallback(async (s: number) => {
    setRes({}); setStatus("Generating simulated study…"); await pause()
    const st = generateStudy(s); setStudy(st)
    const out: Partial<AllResults> = {}
    out.labels = labelStats(st); setRes({ ...out })
    setStatus("C1: leave-one-participant-out (22 folds)…"); await pause(); out.c1 = runC1(st); setRes({ ...out })
    setStatus("C2: population vs personalised models…"); await pause(); out.c2 = runC2(st); setRes({ ...out })
    setStatus("C3: gaze zones and Downward-Gaze Disambiguation…"); await pause(); out.c3 = runC3(st); setRes({ ...out })
    setStatus("C4: forecasting, alert policy, explanations…"); await pause(); out.c4 = runC4(st); setRes({ ...out })
    setStatus("")
  }, [])

  useEffect(() => { run(2026) }, [run])
  // deep link from a component workbench: /research?tab=C3%20Vision
  useEffect(() => {
    const q = new URLSearchParams(window.location.search).get("tab")
    if (q && (TABS as readonly string[]).includes(q)) setTab(q as Tab)
  }, [])

  const download = () => {
    const blob = new Blob([JSON.stringify({ note: "SIMULATED DATA – pipeline demonstration only", seed, results: res }, null, 2)], { type: "application/json" })
    const a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = `focustrack_simulated_results_seed${seed}.json`; a.click()
  }

  const { labels, c1, c2, c3, c4 } = res
  return (
    <AppShell>
      <div className="flex flex-col gap-6">
        <div className="flex flex-wrap items-end justify-between gap-4">
          <div>
            <p className="text-xs font-medium uppercase tracking-[0.2em] text-[#8b6bb0]">Focus Track · Research</p>
            <h1 className="mt-1 flex items-center gap-2 text-3xl font-bold tracking-tight"><FlaskConical className="h-7 w-7 text-[#7b3fa0]" />Analysis pipeline</h1>
            <p className="mt-1 text-sm text-muted-foreground">All four components, run end-to-end with the proposal&apos;s validation design.</p>
          </div>
          <div className="flex items-center gap-2">
            <label className="text-xs text-muted-foreground" htmlFor="seed">Seed</label>
            <input id="seed" type="number" value={seed} onChange={(e) => setSeed(Number(e.target.value))} className="w-24 rounded-xl border border-[#eadfce] bg-white px-2 py-1.5 text-sm" />
            <button onClick={() => run(seed)} disabled={!!status} className="flex items-center gap-1.5 rounded-xl bg-[#7b3fa0] px-3 py-1.5 text-sm font-medium text-white disabled:opacity-50"><RefreshCw className="h-4 w-4" />Re-run</button>
            <button onClick={download} disabled={!!status} className="flex items-center gap-1.5 rounded-xl border border-[#eadfce] bg-white px-3 py-1.5 text-sm font-medium disabled:opacity-50"><Download className="h-4 w-4" />JSON</button>
          </div>
        </div>

        <div className="flex items-start gap-3 rounded-2xl border border-[#f0c9a0] bg-[#fdf1dd] p-4 text-sm text-[#7a4a12]">
          <AlertTriangle className="mt-0.5 h-5 w-5 shrink-0" />
          <p><b>Simulated data.</b> This dataset is generated by a simulator that follows the FocusTrack protocol (22 participants × 6 sessions × 50 minutes, focus probes every 8–12 minutes). It exists to test and demonstrate the analysis pipeline before real data collection. The numbers depend on the simulator&apos;s assumptions and must not be reported as research findings.</p>
        </div>

        {status && <p className="animate-pulse text-sm text-[#7b3fa0]">{status}</p>}

        <div className="flex flex-wrap gap-2">
          {TABS.map((t) => (
            <button key={t} onClick={() => setTab(t)} className={`rounded-full px-4 py-1.5 text-sm font-medium ${tab === t ? "bg-[#2a1840] text-white" : "bg-white text-muted-foreground ring-1 ring-[#eadfce]"}`}>{t}</button>
          ))}
        </div>

        {tab === "Overview & labelling" && labels && (
          <div className="grid gap-4">
            <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
              <Stat label="Participants" value={String(labels.participants)} hint="half usually screen, half non-screen" />
              <Stat label="Sessions" value={String(labels.sessions)} hint={Object.entries(labels.sessionsPerRoom).map(([k, v]) => `${k} ${v}`).join(" · ")} />
              <Stat label="Focus probes" value={String(labels.probes)} hint={`${labels.labelledEpochs} labelled one-minute epochs of ${labels.epochs}`} />
              <Stat label="Observer agreement" value={Number.isFinite(labels.kappa) ? labels.kappa.toFixed(2) : "n/a"} hint={`quadratic-weighted κ on ${labels.observerProbes} library/campus probes`} />
            </div>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Labelling protocol check</h2>
              <p className="mt-1 text-sm text-muted-foreground">Mean probe rating: screen sessions {labels.meanRating.screen.toFixed(2)}, non-screen sessions {labels.meanRating.nonScreen.toFixed(2)}. In the simulator we can also check how well probes track the hidden focus process (Spearman ρ = {labels.probeVsHiddenFocus.toFixed(2)}) – something real data cannot show, which is why the observer audit exists.</p>
            </Card>
            {c4?.sessionTrace && (
              <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
                <h2 className="font-semibold">Example session {c4.sessionTrace.session}</h2>
                <SessionTrace focus={c4.sessionTrace.focus} risk={c4.sessionTrace.risk} probes={c4.sessionTrace.probes} threshold={c4.example?.threshold} alertAt={c4.example?.minute} />
                <Legend items={[{ color: "#1e8e5a", label: "Hidden focus (simulator truth)" }, { color: "#7b3fa0", label: "C4 focus-drop risk" }, { color: "#d9711c", label: "Probe rating (scaled)" }, { color: "#c0392b", label: "Learner's alert threshold / alert" }]} />
              </Card>
            )}
          </div>
        )}

        {tab === "C1 Behaviour" && (c1 ? (
          <div className="grid gap-4 lg:grid-cols-2">
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Macro-F1, leave-one-participant-out</h2>
              <p className="mb-3 text-xs text-muted-foreground">Aggregated counts vs context-aware states + transitions. Paired Wilcoxon across {c1.nParticipants} participants: p = {p3(c1.wilcoxonP)}</p>
              <Bars highlight="Proposed (states + transitions + task)" items={[{ label: "Aggregated baseline", value: c1.baselineF1 }, { label: "Proposed (states + transitions + task)", value: c1.proposedF1 }, ...c1.byMode.flatMap((m) => [{ label: `${m.mode}: baseline`, value: m.baseline }, { label: `${m.mode}: proposed`, value: m.proposed }])]} />
            </Card>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Leave-one-task-out (computer tasks)</h2>
              <p className="mb-3 text-xs text-muted-foreground">Trained on the other tasks, tested on the held-out task.</p>
              <Bars items={c1.loto.flatMap((l) => [{ label: `${l.task}: baseline`, value: l.baseline }, { label: `${l.task}: proposed`, value: l.proposed }])} />
            </Card>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Ablation (same folds)</h2>
              <Bars highlight="Full model" items={c1.ablation.map((a) => ({ label: a.name, value: a.f1 }))} />
            </Card>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Discovered interaction states</h2>
              <p className="mb-2 text-xs text-muted-foreground">Prototype uses k-means states with transition features; the Gaussian HMM replaces it in the final system.</p>
              <table className="w-full text-sm"><thead><tr className="text-left text-xs text-muted-foreground"><th>State</th><th>Keys/min</th><th>Idle</th><th>Switches/min</th><th>Share</th></tr></thead>
                <tbody>{c1.states.map((s) => <tr key={s.state} className="border-t border-[#f3eee6]"><td>S{s.state}</td><td>{s.typing.toFixed(1)}</td><td>{pct(s.idle)}</td><td>{s.switches.toFixed(2)}</td><td>{pct(s.share)}</td></tr>)}</tbody></table>
            </Card>
          </div>
        ) : <Pending />)}

        {tab === "C2 Environment" && (c2 ? (
          <div className="grid gap-4 lg:grid-cols-2">
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Prediction error (MAE, learner-normalised rating)</h2>
              <p className="mb-3 text-xs text-muted-foreground">Trained on sessions 1–4, tested on sessions 5–6 (time split). Lower is better. Personalised vs population paired Wilcoxon p = {p3(c2.personalVsPopulationP)}.</p>
              <Bars max={1.2} highlight="Population model (lags, interaction, covariates)" items={c2.models.map((m) => ({ label: m.name, value: m.mae }))} />
              <p className="mt-3 text-xs text-muted-foreground">A personalised model can lose to the population model when each learner has only ~25 labelled windows – exactly the risk the proposal flags.</p>
            </Card>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Associations with focus (Spearman ρ)</h2>
              <Bars max={0.3} format={(v) => v.toFixed(3)} items={c2.spearman.map((s) => ({ label: s.variable, value: Math.abs(s.rho) }))} />
              <p className="mt-2 text-xs text-muted-foreground">Bar length = |ρ|. Signs: {c2.spearman.map((s) => `${s.variable} ${s.rho >= 0 ? "+" : "−"}`).join(", ")}. Associations, not causes.</p>
            </Card>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm lg:col-span-2">
              <h2 className="font-semibold">Personal comfort bands (training sessions only)</h2>
              <table className="mt-2 w-full text-sm"><thead><tr className="text-left text-xs text-muted-foreground"><th>Learner</th><th>Noise band (dB)</th><th>Temperature band (°C)</th></tr></thead>
                <tbody>{c2.bands.map((b) => <tr key={b.pid} className="border-t border-[#f3eee6]"><td>{b.pid}</td><td>{b.noise.map((v) => (Number.isFinite(v) ? v.toFixed(0) : "–")).join(" – ")}</td><td>{b.temp.map((v) => (Number.isFinite(v) ? v.toFixed(1) : "–")).join(" – ")}</td></tr>)}</tbody></table>
            </Card>
          </div>
        ) : <Pending />)}

        {tab === "C3 Vision" && (c3 ? (
          <div className="grid gap-4 lg:grid-cols-2">
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Downward-Gaze Disambiguation</h2>
              <p className="mb-3 text-xs text-muted-foreground">False &quot;distracted&quot; rate on truly focused minutes in non-screen sessions (lower is better). Relative reduction: {pct(c3.falseDistraction.reduction)}.</p>
              <Bars highlight="With DGD" items={[{ label: "Fixed-angle rule", value: c3.falseDistraction.fixed }, { label: "With DGD", value: c3.falseDistraction.dgd }]} format={pct} />
              <p className="mb-2 mt-4 text-xs text-muted-foreground">Phone-use recall in screen sessions (DGD must not miss distraction):</p>
              <Bars items={[{ label: "Fixed rule", value: c3.phoneRecall.fixed }, { label: "DGD – all", value: c3.phoneRecall.dgd }, { label: "DGD – phone in frame", value: c3.phoneRecall.visible }, { label: "DGD – phone out of frame", value: c3.phoneRecall.outOfFrame }]} format={pct} />
            </Card>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Gaze-zone accuracy (screen / desk / away)</h2>
              <p className="mb-3 text-xs text-muted-foreground">Held-out scripted segments. Generic model trained on other learners vs each learner&apos;s own calibration. Paired Wilcoxon p = {p3(c3.zoneP)}.</p>
              <Bars highlight="Personal calibration" items={[{ label: "Generic model", value: c3.zoneGeneric }, { label: "Personal calibration", value: c3.zonePersonal }]} format={pct} />
            </Card>
          </div>
        ) : <Pending />)}

        {tab === "C4 Temporal & XAI" && (c4 ? (
          <div className="grid gap-4 lg:grid-cols-2">
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Forecasting a focus drop 5–10 min ahead (ROC-AUC)</h2>
              <p className="mb-3 text-xs text-muted-foreground">{c4.rows} forecast points, drop rate {pct(c4.dropRate)}, leave-one-participant-out. Includes the H1 (no vision) and H2 (no context) ablations.</p>
              <Bars highlight="Fused + context (proposed)" items={c4.auc.map((a) => ({ label: a.name, value: a.auc }))} />
            </Card>
            <Card className="border-[#eadfce] bg-white p-5 shadow-sm">
              <h2 className="font-semibold">Alert policy (sessions 4–6)</h2>
              <table className="mt-2 w-full text-sm"><thead><tr className="text-left text-xs text-muted-foreground"><th>Policy</th><th>Recall</th><th>False alerts/h</th><th>Alerts/h</th></tr></thead>
                <tbody>{c4.policy.map((p) => <tr key={p.name} className="border-t border-[#f3eee6]"><td>{p.name}</td><td>{pct(p.recall)}</td><td>{p.falsePerHour.toFixed(1)}</td><td>{p.alertsPerHour.toFixed(1)}</td></tr>)}</tbody></table>
              <p className="mt-2 text-xs text-muted-foreground">Personal thresholds use a grid search here; Bayesian optimisation replaces it in the final system. In the real study the policy is evaluated in phase 2, not on observation data.</p>
            </Card>
            {c4.example && (
              <Card className="border-[#eadfce] bg-white p-5 shadow-sm lg:col-span-2">
                <h2 className="font-semibold">Explained alert – session {c4.example.session}, minute {c4.example.minute}</h2>
                <div className="mt-3 rounded-2xl border-2 border-[#7b3fa0] p-4">
                  <p className="font-semibold text-[#7b3fa0]">{c4.example.message}</p>
                  <p className="mt-1 text-sm">{c4.example.counterfactual}</p>
                  <div className="mt-3 flex gap-2"><span className="rounded-lg bg-[#7b3fa0] px-3 py-1 text-xs font-semibold text-white">Helpful</span><span className="rounded-lg border border-[#7b3fa0] px-3 py-1 text-xs font-semibold text-[#7b3fa0]">Not now</span></div>
                </div>
                <p className="mb-2 mt-4 text-xs text-muted-foreground">Top contributions to the risk (linear attribution, used as the SHAP-style cross-check):</p>
                <Bars max={Math.max(...c4.example.contributions.map((c) => c.value), 0.1)} items={c4.example.contributions.map((c) => ({ label: c.feature, value: c.value }))} />
              </Card>
            )}
          </div>
        ) : <Pending />)}

        {study && <p className="text-xs text-muted-foreground">Seed {study.seed} · {study.sessions.length} sessions · computed in your browser; nothing is uploaded.</p>}
      </div>
    </AppShell>
  )
}

function Pending() {
  return <p className="text-sm text-muted-foreground">Running…</p>
}
